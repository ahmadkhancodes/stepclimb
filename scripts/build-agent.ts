/** Bundles the in-sandbox agent (and the recipes and rules it reads) into one generated module the orchestrator uploads to each sandbox. */
import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { join, relative } from "node:path";
import { build } from "esbuild";

const root = process.cwd();
const walk = (dir: string, out: string[] = []): string[] => { for (const n of readdirSync(dir)) { const p = join(dir, n); if (statSync(p).isDirectory()) walk(p, out); else out.push(p); } return out; };

async function main() {
  const r = await build({
    entryPoints: [join(root, "src/lib/runs/sandbox/agent-main.ts")], bundle: true, platform: "node", format: "esm", target: "node22", write: false, minify: true, legalComments: "none",
    banner: { js: "import { createRequire as __cr } from 'node:module'; const require = __cr(import.meta.url);" },
    logLevel: "warning",
  });
  const files: { path: string; content: string }[] = [{ path: "agent.mjs", content: r.outputFiles[0]!.text }];
  for (const dir of ["recipes", "repair-rules"]) for (const f of walk(join(root, dir))) files.push({ path: `${dir}/${relative(join(root, dir), f)}`, content: readFileSync(f, "utf8") });
  writeFileSync(join(root, "src/lib/runs/sandbox/agent-payload.generated.ts"), `// generated by scripts/build-agent.ts (npm run build:agent); do not edit\nexport const AGENT_FILES: { path: string; content: string }[] = ${JSON.stringify(files)};\n`);
  console.log(`agent payload: ${files.length} files, ${(files[0]!.content.length / 1024).toFixed(0)} KB bundle`);
}
void main();
